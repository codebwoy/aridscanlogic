export function amazonT(lang, key) {
  const pack = AMAZON_STRINGS[lang] || AMAZON_STRINGS.en
  const parts = key.split('.')
  let cur = pack
  for (const p of parts) {
    cur = cur?.[p]
  }
  if (typeof cur === 'string') return cur
  const en = AMAZON_STRINGS.en
  let e = en
  for (const p of parts) {
    e = e?.[p]
  }
  return typeof e === 'string' ? e : key
}
