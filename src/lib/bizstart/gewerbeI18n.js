export function gewerbeStepLabel(stepId, lang) {
  return STEP_LABELS[stepId]?.[lang] || stepId
}

export function gewerbeT(lang, key) {
  const table = STRINGS[lang] || STRINGS.en
  return table[key] ?? STRINGS.en[key] ?? key
}

export function gewerbeProgressPct(stepIndex) {
  return Math.round(((stepIndex + 1) / GEWERBE_WIZARD_STEPS.length) * 100)
}

